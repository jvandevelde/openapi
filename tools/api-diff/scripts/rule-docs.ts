// Generates docs/rules/: one page per rule and an index, from the rule
// registry, src/rules/docs.ts and the test cases (for examples).
//
//   node scripts/rule-docs.ts          write the pages
//   node scripts/rule-docs.ts --check  exit 1 if they are out of date
//
// test/unit/rule-docs.test.ts runs the check.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { load } from 'js-yaml';
import { RULE_DOCS } from '../src/rules/docs.ts';
import { baseRuleId, isImplemented, RULES, type RuleMeta } from '../src/rules/registry.ts';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const CASES = join(ROOT, 'test', 'cases');
export const DOCS_DIR = join(ROOT, 'docs', 'rules');

const SECTIONS: Record<number, string> = {
  1: 'Core variance rules (fallbacks)',
  2: 'Paths and operations',
  3: 'Security',
  4: 'Parameters',
  5: 'Request bodies',
  6: 'Responses',
  7: 'Schemas',
  8: 'References and components',
  9: 'Lifecycle and versions',
  10: 'Docs (annotations only)',
  11: 'Spec and engine notices',
};

/** Findings listed per test case in a rule's Test cases table; longer lists end with "… and N more". */
const MAX_FINDINGS_PER_CASE = 6;

const HEADER = '<!-- Generated by scripts/rule-docs.ts from src/rules/. Do not edit; run `npm run docs`. -->\n\n';

interface CaseInfo {
  name: string;
  description: string;
  findings: { rule: string; severity: string; subject: string }[];
  dir: string;
}

function loadCases(): CaseInfo[] {
  if (!existsSync(CASES)) return [];
  return readdirSync(CASES, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort()
    .map((name) => {
      const dir = join(CASES, name);
      const exp = load(readFileSync(join(dir, 'expected.yaml'), 'utf8')) as { description: string; findings: CaseInfo['findings']; options?: unknown };
      return { name, description: exp.description, findings: exp.findings, dir };
    });
}

/** Line diff (LCS) with `context` unchanged lines around each change. */
export function lineDiff(a: string, b: string, context = 2): string {
  const x = a.replace(/\n$/, '').split('\n');
  const y = b.replace(/\n$/, '').split('\n');
  const n = x.length;
  const m = y.length;
  const lcs: number[][] = Array.from({ length: n + 1 }, () => new Array<number>(m + 1).fill(0));
  for (let i = n - 1; i >= 0; i--) for (let j = m - 1; j >= 0; j--) lcs[i]![j] = x[i] === y[j] ? lcs[i + 1]![j + 1]! + 1 : Math.max(lcs[i + 1]![j]!, lcs[i]![j + 1]!);
  const ops: { t: ' ' | '-' | '+'; s: string }[] = [];
  let i = 0;
  let j = 0;
  while (i < n || j < m) {
    if (i < n && j < m && x[i] === y[j]) ops.push({ t: ' ', s: x[i++]! }), j++;
    else if (i < n && (j >= m || lcs[i + 1]![j]! >= lcs[i]![j + 1]!)) ops.push({ t: '-', s: x[i++]! });
    else ops.push({ t: '+', s: y[j++]! });
  }
  const keep = ops.map((o, k) => o.t !== ' ' || ops.slice(Math.max(0, k - context), k + context + 1).some((p) => p.t !== ' '));
  const out: string[] = [];
  let skipped = false;
  ops.forEach((o, k) => {
    if (keep[k]) {
      if (skipped) out.push('  …');
      skipped = false;
      out.push(`${o.t} ${o.s}`);
    } else skipped = true;
  });
  return out.join('\n');
}

function caseFiles(c: CaseInfo): { label: string; base: string; revision: string }[] {
  const read = (p: string): string => readFileSync(join(c.dir, p), 'utf8');
  if (existsSync(join(c.dir, 'base'))) {
    return readdirSync(join(c.dir, 'base'))
      .sort()
      .filter((f) => existsSync(join(c.dir, 'revision', f)))
      .map((f) => ({ label: f, base: read(`base/${f}`), revision: read(`revision/${f}`) }))
      .filter((f) => f.base !== f.revision);
  }
  const base = existsSync(join(c.dir, 'base.yaml')) ? read('base.yaml') : read('base.json');
  return [{ label: 'openapi.yaml', base, revision: read('revision.yaml') }];
}

function exampleFor(rule: RuleMeta, cases: CaseInfo[]): string {
  const doc = RULE_DOCS[rule.id];
  // Prefer an explicit example, then the case named after the rule, then any case that expects it.
  const expects = (x: CaseInfo): boolean => x.findings.some((f) => baseRuleId(f.rule) === rule.id);
  const c = doc?.example ? cases.find((x) => x.name === doc.example) : (cases.find((x) => x.name === rule.id && expects(x)) ?? cases.find(expects));
  if (!c) return '_No example yet: one is added with the rule\'s test case when the rule is implemented._\n';
  const parts = [`From test case [\`${c.name}\`](../../test/cases/${c.name}/): ${c.description}\n`];
  for (const f of caseFiles(c)) {
    parts.push(`\`${f.label}\`, base → revision:\n\n\`\`\`diff\n${lineDiff(f.base, f.revision)}\n\`\`\`\n`);
  }
  parts.push('Findings:\n');
  for (const f of c.findings) parts.push(`- \`${f.rule}\` · ${f.severity} · ${f.subject}`);
  if (c.findings.length === 0) parts.push('- none');
  return parts.join('\n') + '\n';
}

/** Every test case that expects this rule: each one is a runnable example of a variant or edge case. */
function testCases(rule: RuleMeta, cases: CaseInfo[]): string {
  const rows = cases
    .map((c) => ({ c, found: c.findings.filter((f) => baseRuleId(f.rule) === rule.id) }))
    .filter((x) => x.found.length > 0);
  if (!rows.length) return '_None yet._\n';
  const lines = [
    rows.length === 1 ? 'The example above is the only test case for this rule.' : `${rows.length} test cases expect this rule. Each folder has the base and revision documents and the expected findings; they run with \`npm test\`.`,
    '',
  ];
  if (rows.length > 1) {
    lines.push('| Test case | Expects | What it shows |', '|---|---|---|');
    for (const { c, found } of rows) {
      const shown = found.length > MAX_FINDINGS_PER_CASE ? found.slice(0, MAX_FINDINGS_PER_CASE - 1) : found;
      const more = found.length - shown.length;
      const expects = shown.map((f) => `\`${f.rule}\` · ${f.severity} · ${f.subject.replace(/\|/g, '\\|')}`).join('<br>') + (more ? `<br>… and ${more} more` : '');
      lines.push(`| [\`${c.name}\`](../../test/cases/${c.name}/) | ${expects} | ${c.description.replace(/\|/g, '\\|').replace(/\n/g, ' ')} |`);
    }
  }
  return lines.join('\n') + '\n';
}

function severityText(r: RuleMeta): string {
  const s = typeof r.severity === 'string' ? `\`${r.severity}\`` : `\`${r.severity.in}\` in requests, \`${r.severity.out}\` in responses`;
  return r.sdkProfile ? `${s} · \`--profile sdk\`: \`${r.sdkProfile}\`` : s;
}

function ruleIds(r: RuleMeta): string {
  if (r.variants === 'location') return `\`${r.id}\` (all locations), \`query-${r.id}\`, \`header-${r.id}\`, \`cookie-${r.id}\`. Path parameters use \`${r.id}\`.`;
  if (r.variants === 'direction') return `\`${r.id}\` (both directions), \`${r.id}-in-request\`, \`${r.id}-in-response\``;
  return `\`${r.id}\``;
}

const status = (r: RuleMeta): string => (isImplemented(r) ? `Implemented (M${r.milestone})` : `Planned (M${r.milestone})`);

function page(r: RuleMeta, cases: CaseInfo[]): string {
  const doc = RULE_DOCS[r.id];
  if (!doc) throw new Error(`no docs for rule ${r.id} in src/rules/docs.ts`);
  const lines = [
    `# \`${r.id}\``,
    '',
    r.title,
    '',
    '| | |',
    '|---|---|',
    `| **Kind** | \`${r.kind}\` |`,
    `| **Default severity** | ${severityText(r)} |`,
    `| **Rule IDs** | ${ruleIds(r)} |`,
    `| **Status** | ${status(r)} |`,
    `| **Group** | ${SECTIONS[r.section]} ([RULES.md section ${r.section}](../../RULES.md)) |`,
    '',
    '## What it detects',
    '',
    doc.description,
    '',
    '## Why this default',
    '',
    doc.why,
    '',
    '## Example',
    '',
    exampleFor(r, cases),
    '## Test cases',
    '',
    testCases(r, cases),
    '## Policy options',
    '',
    `Every rule takes \`severity\` (\`error\`, \`warn\`, \`info\` or \`off\`), \`fix\` and \`explanation\` in the policy file${r.variants ? ', for the generic ID or any variant ID above (the more specific ID wins)' : ''}. The policy file arrives in M6; see [POLICY.md](../../POLICY.md).`,
    '',
  ];
  if (doc.options?.length) {
    lines.push('Options for this rule:', '', '| Option | Default | Description |', '|---|---|---|');
    for (const o of doc.options) lines.push(`| \`${o.name}\` | \`${o.default}\` | ${o.description} |`);
    lines.push('');
  }
  lines.push('```yaml', 'rules:', `  ${r.id}: ${typeof r.severity === 'string' ? r.severity : r.severity.out}`, '```', '', '## How to fix', '', doc.fix, '');
  return HEADER + lines.join('\n');
}

function index(): string {
  const lines = [
    '# Rule reference',
    '',
    `All ${RULES.length} rules, with their default severities. ${RULES.filter(isImplemented).length} are implemented; the rest are planned for the milestone shown. Each rule has its own page with what it detects, why it has its default, an example from its test case, policy options and how to fix it.`,
    '',
    'The design behind the rules is in [RULES.md](../../RULES.md). `api-diff rules` prints the same list.',
    '',
  ];
  for (const [num, title] of Object.entries(SECTIONS)) {
    const rules = RULES.filter((r) => r.section === Number(num));
    lines.push(`## ${num}. ${title}`, '', '| Rule | Kind | Default | Status | Summary |', '|---|---|---|---|---|');
    for (const r of rules) {
      const sev = typeof r.severity === 'string' ? r.severity : `${r.severity.in} / ${r.severity.out}`;
      lines.push(`| [\`${r.id}\`](${r.id}.md) | ${r.kind} | ${sev}${r.sdkProfile ? ` (sdk: ${r.sdkProfile})` : ''} | ${isImplemented(r) ? `M${r.milestone} ✅` : `M${r.milestone}`} | ${r.title} |`);
    }
    lines.push('');
  }
  lines.push('Default `in / out`: severity for data clients send (requests) / receive (responses). `(sdk: …)`: severity under `--profile sdk`.', '');
  return HEADER + lines.join('\n');
}

/** All generated files: path relative to docs/rules → contents. */
export function renderRuleDocs(): Map<string, string> {
  const cases = loadCases();
  const out = new Map<string, string>([['README.md', index()]]);
  for (const r of RULES) out.set(`${r.id}.md`, page(r, cases));
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const files = renderRuleDocs();
  if (process.argv.includes('--check')) {
    const stale = [...files].filter(([f, text]) => !existsSync(join(DOCS_DIR, f)) || readFileSync(join(DOCS_DIR, f), 'utf8') !== text).map(([f]) => f);
    const extra = existsSync(DOCS_DIR) ? readdirSync(DOCS_DIR).filter((f) => !files.has(f)) : [];
    if (stale.length || extra.length) {
      console.error(`docs/rules is out of date (${[...stale, ...extra].join(', ')}). Run: npm run docs`);
      process.exit(1);
    }
  } else {
    rmSync(DOCS_DIR, { recursive: true, force: true });
    mkdirSync(DOCS_DIR, { recursive: true });
    for (const [f, text] of files) writeFileSync(join(DOCS_DIR, f), text);
    console.log(`wrote ${files.size} files to docs/rules/`);
  }
}
